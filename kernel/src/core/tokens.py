@dataclass
class Token:
    type: TokenType
    value: Any
    line: int
    column: int
    filename: str


class LexerError(Exception):
    def __init__(self, message: str, filename: str, line: int, column: int):
        self.filename = filename
        self.line = line
        self.column = column
        super().__init__(f"{filename}:{line}:{column}: {message}")
